#!/usr/bin/env python3
"""
hdl_architect.generators.vhdl (`ha gen vhdl`) - Generate VHDL entities and
architectures from the SysML model.

For every definition reachable from --top:

  Subsystem / Fpga (containers)
      Entity + structural architecture, fully generated and overwritten on
      every run. Written to the first file in the container's @HdlSource.
      Children with @HdlSource are instantiated as `entity lib.name`;
      vendor IP and hard macros (no @HdlSource) get a component declaration.

  Rtl / RegisterFile (leaves)
      Entity + skeleton architecture written ONCE, only if the file does not
      exist yet (the last file in @HdlSource; a missing *_pkg.vhd gets an
      empty package). After that the file belongs to the designer and is
      never touched. (Planned: a --check mode that compares an existing
      leaf entity against the model.)

Naming:
  entity       UartTx          -> uart_tx
  instance     tx_core         -> u_tx_core
  port         clk : ClockIn   -> clk            (one signal: port name)
               csr : AxiLite   -> csr_awaddr ... (several: <port>_<signal>)
  net          connect a.p to b.q  -> a_p[_signal]

The generator also checks every connection: matching port types, opposite
directions across a connect, equal directions across a bind (delegation),
unconnected inputs, and undriven boundary outputs. Any problem -> exit 1.

Usage:
  ha gen vhdl --path lib --path ip --path subsystems --path fpgas --top FpgaOne
"""

from __future__ import annotations

import argparse
import re
import textwrap
import sys
from pathlib import Path

from hdl_architect.core.model import Instance, ModelError, Port, Signal, load_ir

CONTAINERS = ("Subsystem", "Fpga")
GENERIC_TYPES = {
    "Integer": "integer",
    "Natural": "natural",
    "Positive": "positive",
    "Real": "real",
    "Boolean": "boolean",
    "String": "string",
}


# ----------------------------------------------------------------------
# naming and formatting
# ----------------------------------------------------------------------
def entity_name(definition: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", definition).lower()


def vhdl_type(sig: Signal) -> str:
    return (
        "std_logic"
        if sig.width is None
        else f"std_logic_vector({sig.width - 1} downto 0)"
    )


def zero(sig: Signal) -> str:
    return "'0'" if sig.width is None else "(others => '0')"


def generic_value(value, sysml_type: str) -> str:
    if sysml_type == "Boolean":
        return "true" if value else "false"
    if sysml_type == "Real":
        return repr(float(getattr(value, "magnitude", value)))
    if sysml_type == "String":
        return f'"{value}"'
    return str(int(getattr(value, "magnitude", value)))


def library_of(inst: Instance) -> str | None:
    return (inst.metadata.get("HdlSource") or {}).get("vhdl_library")


def header(inst: Instance, generated: bool) -> list[str]:
    src = inst.source_file.name if inst.source_file else "?"
    if generated:
        return [
            f"-- {entity_name(inst.definition)}: generated by `ha gen vhdl` from {src}",
            "-- DO NOT EDIT - change the model (its JSON) instead.",
            "",
        ]
    return [
        f"-- {entity_name(inst.definition)}: skeleton generated by `ha gen vhdl` "
        f"from {src}.",
        "-- This file is now yours: `ha gen vhdl` will not overwrite it.",
        "",
    ]


def port_header(p: Port, width: int = 76) -> list[str]:
    """Comment lines naming a port, its interface, its clock facts and its description.

    `-- Processing CSR : Axi4LiteManager (clock clk)`: the port's readable SysML
    name (when it has a shortName) or its identifier, then its `doc`, wrapped
    to the line width."""
    facts = []
    f = p.params.get("frequency_hz")
    if isinstance(f, (int, float)) and f:
        facts.append(f"{f / 1e6:g} MHz")
    cp = p.params.get("clock_port")
    if isinstance(cp, str) and cp:
        facts.append(f"clock {cp}")
    elif p.params.get("synchronous") is False:
        facts.append("asynchronous")
    # the port's readable SysML name ("Processing CSR") when it has one, else its
    # identifier
    head = f"-- {p.title or p.name} : {p.declared or p.type}" + (
        f" ({', '.join(facts)})" if facts else ""
    )
    lines = [head]
    if p.doc:
        lines += [
            "-- " + line for line in textwrap.wrap(" ".join(p.doc.split()), width - 3)
        ]
    return lines


def join_groups(
    groups: list[list[tuple[str, str]]], sep: str, blank: bool
) -> list[str]:
    """Join groups of ("code", text) / ("comment", text) lines: `sep` after every
    code line except the very last one; a blank line between groups if `blank`."""
    flat = []
    for i, g in enumerate(groups):
        if blank and i:
            flat.append(("blank", ""))
        flat += g
    last = max((i for i, (k, _) in enumerate(flat) if k == "code"), default=-1)
    out = []
    for i, (k, t) in enumerate(flat):
        if k == "code" and i != last:
            if "--" in t:  # keep the separator before a trailing comment
                code, comment = t.split("--", 1)
                t = code.rstrip() + sep + "  --" + comment
            else:
                t += sep
        out.append(t)
    return out


def entity_block(inst: Instance, keyword: str = "entity") -> list[str]:
    """`entity x is ... end entity;` or the matching component declaration."""
    name = entity_name(inst.definition)
    out = [f"{keyword} {name} is"]
    gens = [
        (g, inst.generic_types.get(g, "Integer"), v)
        for g, v in inst.generic_defaults.items()
    ]
    if gens:
        w = max(len(g) for g, _, _ in gens)
        lines = []
        for g, t, v in gens:
            default = f" := {generic_value(v, t)}" if v is not None else ""
            lines.append(f"    {g:<{w}} : {GENERIC_TYPES.get(t, 'integer')}{default}")
        out += (
            ["  generic ("] + [line + ";" for line in lines[:-1]] + [lines[-1], "  );"]
        )
    plist = [(n, s) for p in inst.ports for n, s in p.hdl_names()]
    if plist:
        w = max(len(n) for n, _ in plist)
        groups = [
            [("comment", "    " + h) for h in port_header(p)]
            + [
                ("code", f"    {n:<{w}} : {s.direction:<5} {vhdl_type(s)}")
                for n, s in p.hdl_names()
            ]
            for p in inst.ports
        ]
        out += ["  port ("] + join_groups(groups, ";", blank=True) + ["  );"]
    out.append(f"end {keyword};" if keyword == "component" else "end entity;")
    return out


# ----------------------------------------------------------------------
# structural architecture for containers
# ----------------------------------------------------------------------
class Netlist:
    def __init__(self, inst: Instance):
        self.inst = inst
        self.children = {c.name: c for c in inst.children}
        self.boundary = {p.name: p for p in inst.ports}
        self.actual: dict[tuple[str, str, str], str] = (
            {}
        )  # (child, port, signal) -> net
        self.nets: dict[str, Signal] = {}  # internal signals to declare
        self.driven: set[str] = set()  # boundary outputs driven
        self.groups: list[tuple[str, list[str]]] = []  # (connection label, its nets)
        self.problems: list[str] = []

    def _child_port(self, ref: str) -> tuple[Instance, Port]:
        cname, _, pname = ref.partition(".")
        child = self.children.get(cname)
        if child is None:
            raise ModelError(f"{self.inst.definition}: no part '{cname}' (in '{ref}')")
        port = next((p for p in child.ports if p.name == pname), None)
        if port is None:
            raise ModelError(
                f"{self.inst.definition}: {child.definition} has no port "
                f"'{pname}' (in '{ref}')"
            )
        return child, port

    def _boundary_port(self, name: str) -> Port:
        if name not in self.boundary:
            raise ModelError(f"{self.inst.definition}: no boundary port '{name}'")
        return self.boundary[name]

    def bind(self, a: str, b: str) -> None:
        """Delegation: boundary port = child port (either order)."""
        outer, inner = (a, b) if "." not in a else (b, a)
        if "." in outer or "." not in inner:
            # both inside: a bind between two child ports behaves like a connect
            return self.connect(a, b)
        bport = self._boundary_port(outer)
        child, cport = self._child_port(inner)
        where = f"{self.inst.definition}: bind {outer} = {inner}"
        if bport.type != cport.type:
            self.problems.append(f"{where}: type {bport.type} vs {cport.type}")
            return
        bnames = dict((s.name, n) for n, s in bport.hdl_names())
        bsig = {s.name: s for s in bport.signals}
        bad = [s.name for s in cport.signals if bsig[s.name].direction != s.direction]
        if bad:
            self.problems.append(
                f"{where}: directions differ on {len(bad)} signal(s) "
                f"({', '.join(bad[:3])}{', ...' if len(bad) > 3 else ''}); "
                f"a delegating bind needs the same conjugation on both sides"
            )
        for sig in cport.signals:
            self._assign(child.name, cport.name, sig.name, bnames[sig.name], where)
            if sig.direction == "out":
                self.driven.add(bnames[sig.name])

    def connect(self, a: str, b: str) -> None:
        if "." not in a or "." not in b:
            return self.bind(a, b)
        ca, pa = self._child_port(a)
        cb, pb = self._child_port(b)
        where = f"{self.inst.definition}: connect {a} to {b}"
        if pa.type != pb.type:
            self.problems.append(f"{where}: type {pa.type} vs {pb.type}")
            return
        bsig = {s.name: s for s in pb.signals}
        single = len(pa.signals) == 1
        same = [
            s.name
            for s in pa.signals
            if {s.direction, bsig[s.name].direction} != {"in", "out"}
        ]
        if same:
            self.problems.append(
                f"{where}: {len(same)} signal(s) have the same direction on "
                f"both ends ({', '.join(same[:3])}{', ...' if len(same) > 3 else ''}); "
                f"one side should be conjugated (~{pa.type})"
            )
        group: list[str] = []
        self.groups.append((f"{a} <-> {b} : {pa.declared or pa.type}", group))
        for sig in pa.signals:
            other = bsig[sig.name]
            if sig.width != other.width:
                self.problems.append(
                    f"{where}: {sig.name} width {sig.width} vs {other.width}"
                )
            net = (
                f"{ca.name}_{pa.name}" if single else f"{ca.name}_{pa.name}_{sig.name}"
            )
            self.nets[net] = sig
            group.append(net)
            self._assign(ca.name, pa.name, sig.name, net, where)
            self._assign(cb.name, pb.name, sig.name, net, where)

    def _assign(self, child: str, port: str, sig: str, net: str, where: str) -> None:
        key = (child, port, sig)
        if key in self.actual and self.actual[key] != net:
            self.problems.append(
                f"{where}: {child}.{port}.{sig} already connected to "
                f"{self.actual[key]}"
            )
        self.actual[key] = net


def structural(inst: Instance) -> tuple[list[str], list[str]]:
    nl = Netlist(inst)
    for a, b in inst.bindings:
        nl.bind(a, b)
    for a, b in inst.connections:
        nl.connect(a, b)

    libs = sorted({library_of(c) for c in inst.children if library_of(c)})
    out = header(inst, generated=True)
    out += ["library ieee;", "use ieee.std_logic_1164.all;", ""]
    for lib in libs:
        out.append(f"library {lib};")
    if libs:
        out.append("")
    out += entity_block(inst) + [
        "",
        f"architecture structural of {entity_name(inst.definition)} is",
        "",
    ]

    components = []
    for c in inst.children:
        if not library_of(c) and c.definition not in components:
            components.append(c.definition)
            out.append(
                f"  -- {c.kind}: no @HdlSource, so a component is declared. "
                f"Port names follow the model;"
            )
            out.append(
                "  -- map them to the vendor's names in a wrapper if they differ."
            )
            out += ["  " + line for line in entity_block(c, keyword="component")] + [""]

    if nl.nets:
        w = max(len(n) for n in nl.nets)
        seen: set[str] = set()
        for label, nets in nl.groups:
            nets = [n for n in nets if n not in seen]
            if not nets:
                continue
            seen.update(nets)
            out.append(f"  -- {label}")
            out += [f"  signal {n:<{w}} : {vhdl_type(nl.nets[n])};" for n in nets] + [
                ""
            ]
    out.append("begin")

    for c in inst.children:
        if c.count != 1:
            nl.problems.append(
                f"{inst.definition}: {c.name}[{c.count}] - multiplicity "
                f"(for-generate) is not supported yet"
            )
        lib = library_of(c)
        target = (
            f"entity {lib}.{entity_name(c.definition)}"
            if lib
            else entity_name(c.definition)
        )
        out += ["", f"  u_{c.name} : {target}"]
        gens = [(g, v) for g, v in c.generics.items() if v is not None]
        if gens:
            w = max(len(g) for g, _ in gens)
            lines = [
                f"      {g:<{w}} => "
                f"{generic_value(v, c.generic_types.get(g, 'Integer'))}"
                for g, v in gens
            ]
            out += (
                ["    generic map ("]
                + [line + "," for line in lines[:-1]]
                + [lines[-1], "    )"]
            )
        maps, groups = [], []
        for p in c.ports:
            group = []
            groups.append((p, group))
            for hname, sig in p.hdl_names():
                net = nl.actual.get((c.name, p.name, sig.name))
                if net is None:
                    if sig.direction == "in":
                        nl.problems.append(
                            f"{inst.definition}: input {c.name}.{hname} is "
                            f"unconnected"
                        )
                        net = "open  -- UNCONNECTED INPUT"
                    else:
                        net = "open"
                maps.append((hname, net))
                group.append((hname, net))
        if maps:
            w = max(len(n) for n, _ in maps)
            lines = [
                (
                    [("comment", f"      -- {p.name} : {p.declared or p.type}")]
                    if len(g) > 1
                    else []
                )
                + [("code", f"      {n:<{w}} => {a}") for n, a in g]
                for p, g in groups
                if g
            ]
            out += (
                ["    port map ("] + join_groups(lines, ",", blank=False) + ["    );"]
            )

    for p in inst.ports:
        undriven = [
            h for h, s in p.hdl_names() if s.direction == "out" and h not in nl.driven
        ]
        if undriven:
            nl.problems.append(
                f"{inst.definition}: boundary port {p.name} has "
                f"{len(undriven)} undriven output(s) "
                f"({', '.join(undriven[:3])}{', ...' if len(undriven) > 3 else ''})"
            )
    out += ["", "end architecture;", ""]
    return out, nl.problems


# ----------------------------------------------------------------------
# skeletons for leaves
# ----------------------------------------------------------------------
def skeleton(inst: Instance) -> list[str]:
    out = header(inst, generated=False)
    out += [
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use ieee.numeric_std.all;",
        "",
    ]
    out += entity_block(inst)
    out += [
        "",
        f"architecture rtl of {entity_name(inst.definition)} is",
        "begin",
        "",
        "  -- TODO: implement. Outputs are tied off so the skeleton compiles and "
        "simulates.",
        "",
    ]
    for p in inst.ports:
        for hname, sig in p.hdl_names():
            if sig.direction == "out":
                out.append(f"  {hname} <= {zero(sig)};")
    out += ["", "end architecture;", ""]
    return out


def package_stub(path: Path) -> list[str]:
    name = path.stem
    return [
        f"-- {name}: empty package skeleton generated by `ha gen vhdl`. This file is "
        "now yours.",
        "",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "",
        f"package {name} is",
        "end package;",
        "",
    ]


# ----------------------------------------------------------------------
def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="ha gen vhdl",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument(
        "--path",
        action="append",
        dest="paths",
        metavar="DIR",
        required=True,
        help="model search path directory; repeat for several",
    )
    ap.add_argument(
        "--top", required=True, help="top-level part definition, e.g. FpgaOne"
    )
    ap.add_argument(
        "--no-skeletons",
        action="store_true",
        help="only generate container architectures; never create leaf files",
    )
    ap.add_argument("--dry-run", action="store_true", help="report, but write nothing")
    args = ap.parse_args(argv)

    try:
        top = load_ir(args.paths, args.top)
    except ModelError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    seen, problems, written, skipped = set(), [], [], []
    for inst in top.walk_post():
        if inst.definition in seen:
            continue
        seen.add(inst.definition)
        files = [
            Path(f) for f in (inst.metadata.get("HdlSource") or {}).get("files", [])
        ]
        try:
            if inst.kind in CONTAINERS:
                if not files:
                    problems.append(
                        f"{inst.definition}: container has no @HdlSource; "
                        f"nowhere to write its structural architecture"
                    )
                    continue
                text, probs = structural(inst)
                problems += probs
                if not args.dry_run:
                    files[0].parent.mkdir(parents=True, exist_ok=True)
                    files[0].write_text("\n".join(text))
                written.append((files[0], "structural"))
            elif files and not args.no_skeletons:
                for f in files[:-1]:
                    if f.name.endswith("_pkg.vhd") and not f.exists():
                        if not args.dry_run:
                            f.parent.mkdir(parents=True, exist_ok=True)
                            f.write_text("\n".join(package_stub(f)))
                        written.append((f, "package skeleton"))
                entity_file = files[-1]
                if entity_file.exists():
                    skipped.append(entity_file)
                else:
                    if not args.dry_run:
                        entity_file.parent.mkdir(parents=True, exist_ok=True)
                        entity_file.write_text("\n".join(skeleton(inst)))
                    written.append((entity_file, "skeleton"))
        except ModelError as e:
            problems.append(str(e))

    cwd = Path.cwd()
    rel = lambda p: p.relative_to(cwd) if p.is_relative_to(cwd) else p  # noqa: E731
    verb = "would write" if args.dry_run else "wrote"
    for f, what in written:
        print(f"{verb} {rel(f)}  ({what})")
    for f in skipped:
        print(f"kept  {rel(f)}  (exists; owned by the designer)")
    for p in problems:
        print(f"warning: {p}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
