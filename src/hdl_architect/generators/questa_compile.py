#!/usr/bin/env python3
"""
hdl_architect.generators.questa_compile (`ha gen compile`) - Generate a QuestaSim
compile script from the SysML model.

Elaborates the design from a top-level part definition and writes a .do
file that creates every library and compiles every source file in
dependency order:

  * children before parents (post-order over the instance hierarchy),
    so every entity exists before the architecture that instantiates it
  * within a component, files in the order listed in @HdlSource
    (list packages first)
  * each definition compiled once, however many times it is instantiated
  * only definitions reachable from --top are compiled

Source paths in @HdlSource are relative to the model file that declares
them; the .do file writes them relative to --repo (default: current dir).

Components with no @HdlSource (vendor IP, hard macros) are reported and
left as comment hooks in the script, because their simulation models
come from the vendor tool (e.g. Vivado export_simulation / compile_simlib).

Usage:
  ha gen compile --path lib --path ip --path subsystems \
                               --path fpgas --top FpgaOne --out sim/compile.do
  cd sim && vsim -c -do compile.do
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

from hdl_architect.core.model import Instance, ModelError, load_ir

# hdl_language value -> (compiler, flags)
LANGUAGES = {
    "VHDL-2019": ("vcom", "-2019"),
    "VHDL-2008": ("vcom", "-2008"),
    "VHDL-2002": ("vcom", "-2002"),
    "VHDL-93": ("vcom", "-93"),
    "Verilog": ("vlog", ""),
    "SystemVerilog": ("vlog", "-sv"),
}


class CompileError(Exception):
    pass


def compile_plan(top: Instance):
    """Return (ordered [(library, compiler, flags, file, definition)], libraries,
    missing)."""
    plan, seen_defs, file_lib, libraries, missing = [], set(), {}, [], []
    for inst in top.walk_post():
        if inst.definition in seen_defs:
            continue
        seen_defs.add(inst.definition)
        src = inst.metadata.get("HdlSource")
        if not src:
            if inst.kind not in ("Subsystem", "Fpga"):
                missing.append(inst)
            continue
        lang = src.get("hdl_language")
        lib = src.get("vhdl_library")
        files = src.get("files") or []
        if isinstance(files, str):
            files = [files]
        if lang not in LANGUAGES:
            raise CompileError(
                f"{inst.definition}: unknown hdl_language {lang!r} "
                f"(known: {', '.join(LANGUAGES)})"
            )
        if not lib:
            raise CompileError(f"{inst.definition}: @HdlSource has no vhdl_library")
        if not files:
            raise CompileError(f"{inst.definition}: @HdlSource has no files")
        if lib not in libraries:
            libraries.append(lib)
        tool, flags = LANGUAGES[lang]
        for f in files:
            if f in file_lib:
                if file_lib[f] != lib:
                    raise CompileError(
                        f"{f} is listed in library '{file_lib[f]}' "
                        f"and in '{lib}' (by {inst.definition})"
                    )
                continue
            file_lib[f] = lib
            plan.append((lib, tool, flags, f, inst.definition))
    return plan, libraries, missing


def render_do(top_def: str, plan, libraries, missing, root: str, repo: Path) -> str:
    out = [
        "# Generated by `ha gen compile` from the model -- do not edit.",
        f"# Top: {top_def}",
        "#",
        "# Run:  vsim -c -do {this file}",
        "",
        "onerror {quit -code 1}",
        f"set ROOT {root}",
        "",
        "# ---- libraries ----",
    ]
    for lib in libraries:
        out += [f"if {{![file exists {lib}]}} {{ vlib {lib} }}", f"vmap {lib} {lib}"]
    out += ["", "# ---- sources (dependency order) ----"]
    current = None
    for lib, tool, flags, f, defn in plan:
        if defn != current:
            out.append(f"# {defn}")
            current = defn
        flag = f" {flags}" if flags else ""
        rel = Path(os.path.relpath(f, repo)).as_posix()
        out.append(f'{tool}{flag} -work {lib} "$ROOT/{rel}"')
    if missing:
        out += ["", "# ---- no @HdlSource: compile vendor simulation models here ----"]
        for inst in missing:
            ip = inst.metadata.get("IpConfig", {})
            note = f"  vlnv={ip['vlnv']}" if ip.get("vlnv") else ""
            out.append(f"# TODO {inst.definition} ({inst.kind}) at {inst.path}{note}")
    out += ["", "quit -code 0"]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="ha gen compile",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument(
        "--path",
        action="append",
        dest="paths",
        metavar="DIR",
        help="model search path directory; repeat for several " "(default: ./model)",
    )
    ap.add_argument(
        "--top", required=True, help="top-level part definition, e.g. FpgaOne"
    )
    ap.add_argument(
        "--out", default="compile.do", help="output .do file (default: compile.do)"
    )
    ap.add_argument(
        "--repo",
        default=".",
        help="repo root that source paths are written relative to (default: .)",
    )
    ap.add_argument(
        "--root",
        default=None,
        help="path from the .do file's directory to --repo "
        "(default: computed from --out and --repo)",
    )
    ap.add_argument(
        "--check-files",
        action="store_true",
        help="warn about source files that do not exist",
    )
    args = ap.parse_args(argv)

    repo = Path(args.repo).resolve()
    out = Path(args.out)
    root = args.root or Path(os.path.relpath(repo, out.parent.resolve())).as_posix()
    paths = args.paths or [str(Path(__file__).parent / "model")]
    try:
        top = load_ir(paths, args.top)
        plan, libraries, missing = compile_plan(top)
    except (CompileError, ModelError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_do(args.top, plan, libraries, missing, root, repo))

    print(f"wrote {args.out}: {len(libraries)} libraries, {len(plan)} files")
    for lib, _, _, f, defn in plan:
        print(f"  {lib:<14} {os.path.relpath(f, repo):<40} ({defn})")
    for inst in missing:
        print(
            f"  warning: no @HdlSource for {inst.definition} ({inst.kind}) at "
            f"{inst.path}"
        )
    if args.check_files:
        for _, _, _, f, _ in plan:
            if not Path(f).exists():
                print(f"  warning: {os.path.relpath(f, repo)} does not exist")
    return 0


if __name__ == "__main__":
    sys.exit(main())
